



"""
Модуль для обработки текста.
Изменяет регистр в зависимости от первого символа и удаляет спецсимволы.
"""

import re


def process_text(text: str) -> str:
    """
    Обрабатывает строку:
    - Если первый символ '!', приводит к верхнему регистру, иначе к нижнему.
    - Удаляет символы '!', '@', '#', '%'.
    Возвращает обработанную строку.
    """
    # Проверяем, что строка не пустая, и первый символ - '!'
    if text and text[0] == '!':
        text = text.upper()
    else:
        text = text.lower()

    # Удаляем ненужные символы
    clean_text = re.sub(r'[!@#%]', '', text)
    return clean_text


def handle_text_processing() -> None:
    """
    Обертка для меню: читает строки до пустой и выводит обработанный текст.
    """
    print("--- Обработка текста (регистр и спецсимволы) ---")
    print("Вводите строки (пустая строка — завершить):")

    while data := input("> "):
        result = process_text(data)
        print(result)


