


"""
Модуль для демонстрации работы ключевого слова global.
Показывает, как функция может изменять переменную на уровне модуля.
"""


def handle_global_var() -> None:
    """
    Обертка для меню: демонстрация global.
    Создает временную глобальную переменную 'a', увеличивает её на 10
    и удаляет, чтобы не засорять пространство имен.
    """
    print("--- Увеличение числа на 10 (демонстрация global) ---")

    try:
        raw = input("Введите целое число (например, 0): ").strip()
        val = int(raw)
    except ValueError:
        print("Ошибка: нужно ввести целое число.")
        return

    # Создаем глобальную переменную 'a' и присваиваем ей введенное значение
    global a
    a = val

    def f():
        # Указываем, что 'a' — это глобальная переменная, а не локальная
        global a
        a = a + 10

    f()
    print(f"Результат: {a}")

    # ВАЖНО: Удаляем глобальную переменную, чтобы при следующем
    # вызове меню она не сохраняла старое значение!
    del a


if __name__ == "__main__":
    # Изолированный запуск для проверки: python global_var.py
    handle_global_var()