



"""
Модуль для фильтрации текста по сложным условиям.
Убирает пунктуацию, приводит к нижнему регистру и выводит слова,
которые состоят из 5+ символов, имеют 4+ уникальных символа и встречаются > 2 раз.
"""

import re


def handle_word_filter() -> None:
    """
    Запрашивает текст, фильтрует слова по заданным правилам
    и выводит подходящие слова в алфавитном порядке (каждое с новой строки).
    """
    print("--- Сложная фильтрация слов ---")
    print("Введите текст (можно вставить большой абзац):")
    user_text = input().lower()

    if not user_text.strip():
        print("Ошибка: текст не введен.")
        return

    # Убираем пунктуационные знаки и разбиваем на слова
    # Обрати внимание: внутри квадратных скобок не нужно экранировать большинство символов
    pattern = r"[!,.?;:#$%^&*()]"
    clean_words = re.sub(pattern, "", user_text).split()

    counts: dict[str, int] = {}

    # Считаем частоту только тех слов, которые проходят фильтр по длине и уникальности
    for word in clean_words:
        if len(word) >= 5 and len(set(word)) >= 4:
            counts[word] = counts.get(word, 0) + 1

    # Отбираем слова, которые встретились более 2 раз
    result = [word for word, count in counts.items() if count > 2]

    if not result:
        print("Подходящих слов не найдено.")
        return

    # Сортируем по алфавиту и выводим
    result.sort()
    print("\nРезультат (подходящие слова):")
    for word in result:
        print(word)


