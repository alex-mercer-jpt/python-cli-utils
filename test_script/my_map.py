


"""
Модуль для демонстрации собственной реализации map().
Создает генератор, который применяет переданную функцию к последовательности.
"""


def my_map(func, seq):
    """
    Генераторная функция, аналог встроенной map().
    Применяет функцию func к каждому элементу последовательности seq.
    """
    for i in seq:
        yield func(i)


def handle_my_map() -> None:
    """
    Обертка для меню: запрашивает границы range, применяет лямбда-функцию x**2
    и выводит результат с помощью собственной реализации my_map.
    """
    print("--- Своя реализация map() ---")
    print("Применяем функцию x**2 к диапазону чисел.")

    try:
        start = int(input("Начало диапазона (например, -10): "))
        stop = int(input("Конец диапазона (например, 11): "))
        step = int(input("Шаг (например, 2): "))

        # Создаем лямбда-функцию для возведения в квадрат
        square_func = lambda x: x ** 2

        # Создаем последовательность
        sequence = range(start, stop, step)

        print("\nРезультат:")
        # Применяем нашу функцию my_map и выводим результаты
        for x in my_map(square_func, sequence):
            print(x)

    except ValueError:
        print("Ошибка: нужно вводить целые числа.")


if __name__ == "__main__":
    # Изолированный запуск для проверки: python my_map.py
    handle_my_map()