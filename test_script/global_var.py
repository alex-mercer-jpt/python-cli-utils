


"""
Модуль для демонстрации работы ключевого слова global.
Показывает, как функция может изменять переменную на уровне модуля.
"""

# Глобальная переменная, которая будет хранить состояние между вызовами
GLOBAL_COUNTER = 0


def handle_global_var() -> None:
    """Демонстрация работы global: счетчик вызовов с прибавлением числа."""
    global GLOBAL_COUNTER

    try:
        user_num = int(input("Введите число, которое прибавим к счетчику: "))
    except ValueError:
        print("Ошибка: нужно ввести целое число.")
        return

    # Вот здесь мы меняем глобальную переменную!
    GLOBAL_COUNTER += user_num

    print(f"Вы вызвали эту функцию и добавили {user_num}.")
    print(f"Текущее значение глобального счетчика: {GLOBAL_COUNTER}")