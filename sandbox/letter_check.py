


"""
Модуль для проверки строки на «правильность».
Строка считается правильной, если в ней есть 'a' или 'o', но нет 'i' и 'e'.
"""


def handle_letter_check() -> None:
    """
    Запрашивает строку (в нижнем регистре) и выводит True или False
    в зависимости от наличия/отсутствия определенных букв.
    """
    print("Проверка строки на наличие 'a' или 'o' и отсутствие 'i' и 'e'.")

    # Считываем строку и сразу приводим к нижнему регистру на случай, если введут заглавные
    user_text = input("Введите строку (только латинские буквы например: 'letter'): ").strip().lower()

    if not user_text:
        print("Пустая строка.")
        return

    # Условие: (есть 'a' ИЛИ есть 'o') И (нет 'i' И нет 'e')
    is_correct = ('a' in user_text or 'o' in user_text) and \
                 ('i' not in user_text and 'e' not in user_text)

    print(is_correct)



