


"""
Модуль для очистки текста.
Приводит строку к нижнему регистру и удаляет символы '!', '%', '#', '@'.
"""

import re

def handle_clean_text() -> None:
    """
    Запрашивает строку, очищает её от спецсимволов и выводит:
    1. Количество удаленных символов.
    2. Очищенную строку.
    """
    print("--- Очистка текста от спецсимволов ---")
    user_text = input("Введите текст (например, Hello World!@#%): ")

    # Приводим к нижнему регистру
    user_text = user_text.lower()

    # Паттерн: ищем символы !, %, #, @
    # В регулярках не обязательно использовать квадратные скобки для простых символов
    # re.subn возвращает кортеж: (очищенная_строка, количество_замен)
    cleaned_text, replacement_count = re.subn(r"[!%#@]", "", user_text)

    print(f"Заменено символов: {replacement_count}")
    print(f"Результат: {cleaned_text}")


