

"""
Модуль для приветствия пользователя по имени.
Запрашивает имя, проверяет на пустоту и выводит приветствие.
"""


def handle_hello() -> None:
    """
    Запрашивает имя у пользователя и выводит приветствие.

    Если пользователь ввел пустую строку (или только пробелы),
    выводит сообщение об ошибке.
    """
    user_name = input("Введите ваше имя: ").strip()

    if not user_name:
        print("Имя не введено")
        return

    print(f"Hello, {user_name}")


if __name__ == "__main__":
    # Изолированный запуск для проверки: python hello_name.py
    handle_hello()