


"""
Модуль для демонстрации map() и лямбда-функции.
Преобразует числа из range: нечетные возводит в квадрат, четные делает отрицательными.
"""


def handle_map_lambda_range() -> None:
    """
    Запрашивает три числа (start, stop, step) для range().
    Применяет лямбда-функцию к каждому числу и выводит результат.
    """
    print("--- Демонстрация map() и lambda (нечетные в квадрат, четные с минусом) ---")
    raw_input = input("Введите начало, конец и шаг через пробел (например, 1 10 1): ").strip()

    try:
        # Распаковываем ровно 3 значения
        start, stop, step = map(int, raw_input.split())
    except ValueError:
        print("Ошибка: нужно ввести ровно три целых числа.")
        return

    # Применяем лямбда-функцию к каждому элементу range
    # Если x нечетное (x % 2 != 0), возвращаем x ** 2
    # Иначе (x четное), возвращаем -x
    result = map(lambda x: x ** 2 if x % 2 != 0 else -x, range(start, stop, step))

    print("Результат:")
    for i in result:
        print(i)


