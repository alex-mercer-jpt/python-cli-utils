


"""
Модуль для демонстрации форматирования чисел.
Считывает три числа и выводит их в заданных форматах:
знаковый, с плавающей точкой и в двоичной системе.
"""


def handle_number_formatting() -> None:
    """
    Запрашивает три числа и выводит их в разных форматах.
    1. Целое число (с принудительным знаком + или -)
    2. Число с плавающей точкой (заполнение решетками, 2 знака после запятой)
    3. Целое число (перевод в двоичную систему, заполнение нулями и подчеркиваниями)
    """
    print("--- Демонстрация форматирования чисел ---")

    try:
        number_1 = int(input("Введите 1-е целое число (например, 102): "))
        number_2 = float(input("Введите 2-е число с точкой (например, 3.14159): "))
        number_3 = int(input("Введите 3-е целое число (например, 1127): "))
    except ValueError:
        print("Ошибка: введены некорректные числа.")
        return

    print("\nРезультат:")

    # 1. {:+010} — добавляет знак (+/-), делает длину строки 10, заполняет нулями
    # Пример: 102 -> +000000102
    print(f"{number_1:0=+10}")

    # 2. {:#>10.2f} — выравнивание по правому краю, заполнение символом '#', 2 знака после запятой
    # Пример: 3.1415926535 -> ######3.14
    print(f"{number_2:#>10.2f}")

    # 3. {:_>19_b} — выравнивание по правому краю (длина 19), заполнение '_', перевод в двоичный формат (b)
    # Пример: 1127 -> 0000_0100_0110_0111
    print(f"{number_3:_>19_b}")


if __name__ == "__main__":
    # Изолированный запуск для проверки: python number_formatting.py
    handle_number_formatting()