


"""
Модуль для поиска максимальных значений в последовательностях.
Считывает N строк с числами, находит в каждой строке максимум,
сортирует максимумы по убыванию и выводит через ';'.
"""


def handle_max_values() -> None:
    """
    Запрашивает количество записей (N), затем сами записи.
    В каждой записи находит максимальное число.
    Выводит отсортированный по убыванию список максимумов через ';'.
    """
    print("--- Поиск максимумов в последовательностях ---")

    try:
        n = int(input("Сколько записей (строк) нужно обработать? (например, 3): "))
        if n < 1:
            print("Ошибка: количество записей должно быть больше 0.")
            return
    except ValueError:
        print("Ошибка: нужно ввести целое число.")
        return

    maxes = []
    print(f"Введите {n} строк(и) с числами через пробел:")

    for i in range(n):
        try:
            raw_data = input(f"  Строка {i + 1}: ")
            # Превращаем строку в список чисел
            nums = [int(x) for x in raw_data.split()]

            if not nums:
                print("Ошибка: строка не должна быть пустой. Пропускаю.")
                continue

            maxes.append(max(nums))
        except ValueError:
            print("Ошибка: в строке должны быть только целые числа. Пропускаю.")
            continue

    if not maxes:
        print("Не было введено ни одного корректного набора чисел.")
        return

    # Сортируем по убыванию
    maxes.sort(reverse=True)

    # Превращаем числа обратно в строки и склеиваем через ';'
    # (можно использовать генератор вместо map, это современнее: ';'.join(str(x) for x in maxes))
    result = ";".join(str(x) for x in maxes)

    print(f"Результат: {result}")


if __name__ == "__main__":
    # Изолированный запуск для проверки: python max_values.py
    handle_max_values()