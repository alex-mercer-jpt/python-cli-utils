


"""
Модуль для поиска уникальных символов в строке.
Приводит строку к нижнему регистру, убирает пробелы,
находит уникальные символы и выводит их по возрастанию через пробел.
"""


def handle_unique_chars() -> None:
    """
    Запрашивает строку, находит уникальные символы (без пробелов),
    сортирует их лексикографически и выводит через пробел.
    """
    print("--- Уникальные символы в строке ---")
    raw_text = input("Введите строку (например, abcabcaaabb12bbbaaa): ")

    # Приводим к нижнему регистру и удаляем все пробелы
    # (replace(" ", "") удалит все пробелы, а не только по краям)
    cleaned_text = raw_text.lower().replace(" ", "")

    if not cleaned_text:
        print("Ошибка: строка пуста (или состоит только из пробелов).")
        return

    # set() убирает дубликаты, sorted() сортирует по возрастанию
    unique_chars = sorted(set(cleaned_text))

    # Склеиваем символы через пробел
    result = " ".join(unique_chars)

    print(f"Результат: {result}")


if __name__ == "__main__":
    # Изолированный запуск для проверки: python unique_chars.py
    handle_unique_chars()