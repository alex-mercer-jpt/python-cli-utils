



"""
Модуль для демонстрации собственной реализации filter().
Создает генератор, который фильтрует последовательность на основе переданной функции.
"""


def my_filter(func, seq):
    """
    Генераторная функция, аналог встроенной filter().
    Оставляет только те элементы, для которых func(i) возвращает True.
    """
    for i in seq:
        if func(i):
            yield i


def handle_my_filter() -> None:
    """
    Обертка для меню: запрашивает числа через запятую,
    применяет лямбда-функцию (оставляет положительные) и выводит результат.
    """
    print("--- Своя реализация filter() ---")
    print("Фильтрация чисел (оставляем только положительные).")

    try:
        # 1. Просим пользователя ввести числа через запятую
        raw_input = input("Введите числа через запятую (например, 1, 2, 0, 3, -1, -2, 5): ")

        # 2. Превращаем строку в список чисел
        # split(',') разбивает по запятым, strip() убирает пробелы, int() делает числами
        seq = [int(i.strip()) for i in raw_input.split(",")]

        # 3. Задаем лямбда-функцию (условие фильтрации)
        condition = lambda x: x > 0

        print("\nРезультат:")
        # 4. Применяем my_filter и выводим
        for x in my_filter(condition, seq):
            print(x)

    except ValueError:
        print("Ошибка: нужно вводить целые числа, разделенные запятыми.")


